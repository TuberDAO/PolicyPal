-- PolicyPal — Storage bucket + RLS for case-files
-- Migration: 20260420000000_storage_case_files_rls
--
-- Codifies the case-files Storage bucket as PRIVATE and adds RLS policies on
-- storage.objects that mirror the ownership/staff logic already enforced on
-- public.case_files. Making this reproducible in migrations removes the
-- manual-dashboard-setup failure mode and guarantees the bucket is never
-- unintentionally public.
--
-- Path convention: src/actions/upload.ts writes objects at
--   `${caseId}/${fileId}_${sanitized}`
-- so split_part(name, '/', 1) is the case UUID. The helper below validates
-- that shape and fails CLOSED (returns NULL) on malformed paths so the
-- policies simply do not match rather than erroring out on an unexpected
-- object name. Staff always retain access regardless of path shape.

-- =============================================================================
-- BUCKET — ensure exists and is private
-- =============================================================================

INSERT INTO storage.buckets (id, name, public)
VALUES ('case-files', 'case-files', false)
ON CONFLICT (id) DO UPDATE SET public = false;

-- =============================================================================
-- HELPER — extract case_id from a storage object name, safely
-- =============================================================================
-- Returns the UUID at the first path segment, or NULL if the name does not
-- match the expected `<uuid>/...` layout. Using a plpgsql wrapper with an
-- EXCEPTION block guarantees policy predicates can never raise on unexpected
-- input (e.g. empty name, missing slash, non-UUID prefix).

CREATE OR REPLACE FUNCTION public.case_file_case_id(object_name text)
RETURNS uuid
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  first_segment text;
  result uuid;
BEGIN
  IF object_name IS NULL THEN
    RETURN NULL;
  END IF;

  first_segment := split_part(object_name, '/', 1);

  -- split_part returns '' when no separator is found; guard that explicitly
  -- so we don't feed an empty string into uuid casting.
  IF first_segment IS NULL OR first_segment = '' OR position('/' in object_name) = 0 THEN
    RETURN NULL;
  END IF;

  BEGIN
    result := first_segment::uuid;
  EXCEPTION WHEN others THEN
    RETURN NULL;
  END;

  RETURN result;
END;
$$;

-- =============================================================================
-- ENABLE RLS on storage.objects
-- =============================================================================
-- Supabase already enables RLS on storage.objects by default. This statement
-- is a no-op in that case but keeps the migration self-contained.

ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

-- =============================================================================
-- POLICIES — case-files bucket
-- =============================================================================
-- All policies are scoped to bucket_id = 'case-files' so they cannot affect
-- any other bucket. Each policy uses public.case_file_case_id(name) which
-- fails-closed (returns NULL) on malformed paths, so a bad object name
-- simply does not satisfy the policy — it does not raise.

-- Drop-if-exists keeps this migration replayable in local dev environments
-- that may have been bootstrapped manually.
DROP POLICY IF EXISTS "case-files: owner or staff can read"   ON storage.objects;
DROP POLICY IF EXISTS "case-files: owner or staff can insert" ON storage.objects;
DROP POLICY IF EXISTS "case-files: owner or staff can delete" ON storage.objects;

-- SELECT: customers can read objects whose first path segment is a case they
-- own; staff can read any object in the bucket.
CREATE POLICY "case-files: owner or staff can read"
  ON storage.objects FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'case-files'
    AND (
      public.is_staff()
      OR EXISTS (
        SELECT 1
        FROM public.cases c
        WHERE c.id = public.case_file_case_id(storage.objects.name)
          AND c.customer_id = auth.uid()
      )
    )
  );

-- INSERT: customers can upload only to their own case, and only while that
-- case is in a state that accepts uploads ('draft' or 'awaiting_info'). This
-- mirrors the public.case_files INSERT policy. Staff can upload to any case.
--
-- (The application currently uploads via a signed URL generated by the admin
-- client, which bypasses RLS. This policy is defense-in-depth for any
-- authenticated-context upload path.)
CREATE POLICY "case-files: owner or staff can insert"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'case-files'
    AND (
      public.is_staff()
      OR EXISTS (
        SELECT 1
        FROM public.cases c
        WHERE c.id = public.case_file_case_id(storage.objects.name)
          AND c.customer_id = auth.uid()
          AND c.status IN ('draft', 'awaiting_info')
      )
    )
  );

-- DELETE: customers can delete only objects belonging to their own cases;
-- staff can delete any object in the bucket.
CREATE POLICY "case-files: owner or staff can delete"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'case-files'
    AND (
      public.is_staff()
      OR EXISTS (
        SELECT 1
        FROM public.cases c
        WHERE c.id = public.case_file_case_id(storage.objects.name)
          AND c.customer_id = auth.uid()
      )
    )
  );
